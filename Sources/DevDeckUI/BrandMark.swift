/// The vendors' own marks, as the path data from their SVGs.
///
/// Copied rather than approximated: a hand-drawn impression of the octocat at fourteen points
/// looks exactly like what it is. Each of these is the `d` attribute out of the vendor's file,
/// with the viewBox it was authored in, so the card draws the real logo.
///
/// Tinted in the brand's own colour where that colour survives dark glass. GitHub's mark is
/// black, which would vanish, so it goes white - which is what GitHub does on dark backgrounds
/// itself.
public enum BrandMark {
    public struct Vector {
        public let paths: [String]
        public let viewBox: CGSize
        public let color: Color
        /// DDEV draws its mark as outlines cut out of solid shapes.
        public let isEvenOdd: Bool

        public init(paths: [String], viewBox: CGSize, color: Color, isEvenOdd: Bool = false) {
            self.paths = paths
            self.viewBox = viewBox
            self.color = color
            self.isEvenOdd = isEvenOdd
        }
    }

    public static let github = Vector(
        paths: [githubPath],
        viewBox: CGSize(width: 24, height: 24),
        color: .white
    )

    public static let node = Vector(
        paths: [nodePath],
        viewBox: CGSize(width: 24, height: 24),
        color: Color(red: 0.549, green: 0.784, blue: 0.294)
    )

    public static let docker = Vector(
        paths: [dockerPath],
        viewBox: CGSize(width: 24, height: 24),
        color: Color(red: 0.145, green: 0.588, blue: 0.929)
    )

    public static let ddev = Vector(
        paths: ddevPaths,
        viewBox: CGSize(width: 261.16, height: 199.3),
        color: Color(red: 0.008, green: 0.659, blue: 0.886),
        isEvenOdd: true
    )
}

